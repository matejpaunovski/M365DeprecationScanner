#Requires -Version 7.0
<#
.SYNOPSIS
    Generates the Markdown rule catalog (docs/rules.md) from the rule database.
.DESCRIPTION
    Do not edit docs/rules.md by hand. Change src/M365DeprecationScanner/Data/deprecations.json and run
    ./build.ps1 -Task Docs. CI fails when the catalog is out of date.
.OUTPUTS
    System.String
#>
[CmdletBinding()]
[OutputType([string])]
param(
    [string]$DatabasePath = (Join-Path (Split-Path $PSScriptRoot -Parent) 'src/M365DeprecationScanner/Data/deprecations.json')
)

$ErrorActionPreference = 'Stop'
$database = Get-Content -LiteralPath $DatabasePath -Raw -Encoding UTF8 | ConvertFrom-Json

function Format-Cell {
    param([AllowNull()][string]$Text)
    if ([string]::IsNullOrEmpty($Text)) { return '' }
    return ($Text -replace '\r?\n', ' ' -replace '\|', '\|')
}

function Format-Code {
    param([AllowNull()][string]$Text)
    if ([string]::IsNullOrEmpty($Text)) { return '' }
    if ($Text -match '[`|]') { return Format-Cell $Text }
    return '`' + $Text + '`'
}

$areaTitles = [ordered]@{
    MSOnline       = 'MSOnline module'
    AzureAD        = 'AzureAD / AzureADPreview modules'
    ExchangeOnline = 'Exchange Online'
    MicrosoftGraph = 'Microsoft Graph PowerShell SDK'
    AzureADGraph   = 'Azure AD Graph API'
    Azure          = 'Azure (AzureRM / Az)'
    Teams          = 'Microsoft Teams'
    SharePoint     = 'SharePoint Online'
    Intune         = 'Intune'
    Other          = 'Other'
}
$statusIcons = @{ Retired = ':red_circle: Retired'; Deprecated = ':orange_circle: Deprecated'; Announced = ':large_blue_circle: Announced' }

$rules = @($database.rules)
$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('<!-- This file is generated by tools/New-RuleCatalog.ps1. Do not edit it by hand. -->')
[void]$builder.AppendLine('# Rule catalog')
[void]$builder.AppendLine()
[void]$builder.AppendLine(('**{0} rules**, last updated **{1}**.' -f $rules.Count, $database.lastUpdated))
[void]$builder.AppendLine()
[void]$builder.AppendLine('| Status | Severity | Meaning |')
[void]$builder.AppendLine('|---|---|---|')
[void]$builder.AppendLine('| :red_circle: Retired | Error | No longer works. Fix now. |')
[void]$builder.AppendLine('| :orange_circle: Deprecated | Warning | Still works, but support has ended or retirement is announced. Fix soon. |')
[void]$builder.AppendLine('| :large_blue_circle: Announced | Information | Retirement announced for a future date. Plan ahead. |')
[void]$builder.AppendLine()
[void]$builder.AppendLine('Look up a single command from PowerShell: `Get-M365DeprecationRule -Name Get-MsolUser`')
[void]$builder.AppendLine()
[void]$builder.AppendLine('Found a mistake or a missing rule? See [CONTRIBUTING.md](../CONTRIBUTING.md#adding-or-changing-a-rule).')
[void]$builder.AppendLine()

$presentAreas = @($areaTitles.Keys | Where-Object { $area = $_; @($rules | Where-Object area -EQ $area).Count -gt 0 })
[void]$builder.AppendLine('## Contents')
[void]$builder.AppendLine()
foreach ($area in $presentAreas) {
    $count = @($rules | Where-Object area -EQ $area).Count
    $anchor = ($areaTitles[$area].ToLowerInvariant() -replace '[^a-z0-9 -]', '' -replace ' ', '-')
    [void]$builder.AppendLine(('- [{0}](#{1}) ({2})' -f $areaTitles[$area], $anchor, $count))
}
[void]$builder.AppendLine()

foreach ($area in $presentAreas) {
    [void]$builder.AppendLine("## $($areaTitles[$area])")
    [void]$builder.AppendLine()
    [void]$builder.AppendLine('| Id | Kind | Pattern | Status | Retirement | Use instead | Source |')
    [void]$builder.AppendLine('|---|---|---|---|---|---|---|')
    foreach ($rule in ($rules | Where-Object area -EQ $area)) {
        $pattern = if ($rule.kind -eq 'Parameter') { '{0} -{1}' -f $rule.command, $rule.pattern } else { $rule.pattern }
        $retirement = if ($rule.PSObject.Properties['retirementDate']) { $rule.retirementDate } else { '' }
        $sourceList = @($rule.sources)
        $sources = @(for ($n = 0; $n -lt $sourceList.Count; $n++) { '[{0}]({1})' -f ($n + 1), $sourceList[$n] }) -join ' '
        [void]$builder.AppendLine(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} |' -f $rule.id, $rule.kind, (Format-Code $pattern), $statusIcons[$rule.status], $retirement, (Format-Code $rule.replacement), $sources))
    }
    [void]$builder.AppendLine()
}

$builder.ToString().TrimEnd() + [Environment]::NewLine
